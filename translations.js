function translateProducts(lang) {
    // 1. Translate category headers
    document.querySelectorAll('.category-title, .mobile-menu div, .dropdown-content a, .mobile-subcategories a').forEach(el => {
        let originalText = el.getAttribute('data-original-text');
        if (!originalText) {
            originalText = el.innerText.trim().replace(/^- /, ''); // clean mobile dashes
            el.setAttribute('data-original-text', originalText);
        }

        if (lang === 'en' && categoryTranslations[originalText]) {
            const isSubCategory = el.innerText.startsWith('- ');
            el.innerText = (isSubCategory ? '- ' : '') + categoryTranslations[originalText];
        } else {
            const isSubCategory = el.innerText.startsWith('- ');
            el.innerText = (isSubCategory ? '- ' : '') + originalText;
        }
    });

    // 2. Translate product cards
    document.querySelectorAll('.product-card').forEach(card => {
        // Title
        const titleEl = card.querySelector('h4');
        if (titleEl) {
            let originalTitle = titleEl.getAttribute('data-original-title');
            if (!originalTitle) {
                originalTitle = titleEl.innerText.trim();
                titleEl.setAttribute('data-original-title', originalTitle);
            }
            if (lang === 'en' && productTranslations[originalTitle]) {
                titleEl.innerText = productTranslations[originalTitle];
            } else {
                titleEl.innerText = originalTitle;
            }
            
            // Also update lightbox data attributes if present in this card
            const viewBtn = card.querySelector('.lightbox-trigger');
            if (viewBtn) {
                viewBtn.setAttribute('data-caption', titleEl.innerText);
            }
        }

        // Price currency conversion visual cue
        const priceEl = card.querySelector('.price');
        if (priceEl) {
            let originalPrice = priceEl.getAttribute('data-original-price');
            if (!originalPrice) {
                originalPrice = priceEl.innerText.trim();
                priceEl.setAttribute('data-original-price', originalPrice);
            }
            if (lang === 'en') {
                priceEl.innerText = originalPrice.replace(' TL', ' TRY');
            } else {
                priceEl.innerText = originalPrice;
            }
        }
    });
}

function setLanguage(lang) {
    if (!translations[lang]) return;
    
    currentLang = lang;
    localStorage.setItem('language', lang);
    document.documentElement.lang = lang;

    // 1. Static element translations
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang][key]) {
            el.innerText = translations[lang][key];
        }
    });

    // 2. Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (placeholders[lang][key]) {
            el.placeholder = placeholders[lang][key];
        }
    });

    // 3. Category & Product details
    translateProducts(lang);

    // 4. Hero Banner Image translation
    const heroImg = document.querySelector('.hero-banner img');
    if (heroImg) {
        if (lang === 'en') {
            heroImg.src = 'assets/hero-banner-en.jpg';
            heroImg.alt = 'Handmade Crocheted with Love - Elegant Crochet';
        } else {
            heroImg.src = 'assets/hero-banner-yeni.jpg';
            heroImg.alt = 'El Emeği Sevgiyle Örüldü - Elegant Crochet';
        }
    }

    // 5. Update language toggler active highlights
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Dispatch custom event to notify scripts (e.g. galeri.js) that language has changed
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));

}

// Auto-run on load
document.addEventListener('DOMContentLoaded', () => {
    // Read preference or fallback to TR
    setLanguage(currentLang);
});

// Expose to window for inline calls
window.setLanguage = setLanguage;
window.translations = translations;
window.currentLang = currentLang;
